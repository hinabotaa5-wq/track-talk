-- #514：旧方式の平文列 identity_vault.disclosures.phone を削除する（#440 の残件）。
--
-- 電話番号は 002 以降、身元情報の暗号化列（identities.phone_enc）に保持し、公開表示もそこから復号する。
-- 専用サービスはこの列を読まない。#514 以降のコードは書きもしない（それ以前のコードは NULL で上書きしていた）。
-- 列を消すことで、金庫の輸出・バックアップにも平文の電話番号が残らなくなる。列の CHECK 制約も一緒に消える。
--
-- 適用順の注意：この列に NULL を書く旧コードの専用サービスが動いている金庫に先に当てると、公開許可の
-- 書き込みが失敗する。#514 のコードの専用サービスを配備してから当てること。
-- 列の削除だけで、他の列・行・権限・RLS には触れない。何度流しても同じ結果になる。
ALTER TABLE identity_vault.disclosures DROP COLUMN IF EXISTS phone;
