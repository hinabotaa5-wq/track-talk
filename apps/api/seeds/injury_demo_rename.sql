-- 本番に入っているケガのデモ用プロフィール(81人、ニックネームが「デモ1」〜「デモ81」)を、1文字のいろいろな名前に変える。
-- injury_demo.sql の名前と同じ並び。ニックネーム以外は変えない。何度流しても同じ結果になる。
-- 実行: psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f apps/api/seeds/injury_demo_rename.sql
BEGIN;

UPDATE profiles p
SET nickname = v.nickname
FROM (
    SELECT n, (ARRAY['空', '海', '陽', '光', '風', '雪', '星', '月', '花', '葉', '岳', '川', '森', '雲', '虹', '波', '翼', '蓮', '葵', '凛', '蒼', '楓', '梓', '茜', '藍', '紬', '桜', '梅', '杏', '桃', '柚', '栞', '咲', '舞', '萌', '彩', '琴', '結', '凪', '響', '颯', '楽', '駿', '隼', '稜', '瑛', '嵐', '朔', '旭', '晴', '暁', '彗', '昴', '慧', '凱', '剛', '烈', '漣', '湊', '柊', '樹', '大', '悠', '碧', '渚', '汐', '凜', '澪', '莉', '彰', '誠', '悟', '匠', '巧', '叶', '玲', '雅', '嘉', '紗', '穂', '祐'])[n] AS nickname
    FROM generate_series(1, 81) AS n
) v
WHERE p.id = ('00000000-0000-4000-8000-' || lpad(v.n::text, 12, '0'))::uuid;

COMMIT;
